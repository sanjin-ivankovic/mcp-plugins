"""Regenerate docs/TOOLS.md and the eval mocks' tool lists from the registered tools.

uv run python tools/gen_tools_doc.py
"""

import asyncio
import json
import textwrap
from pathlib import Path

from mcp import Client

from homelab_mcp import config, docmost, opengist, searxng, server, silverbullet

HEADER = """# Tools of the custom servers

Generated by `plugins/homelab/server/tools/gen_tools_doc.py`; do not edit by
hand. Each heading carries the tool's title. Every `homelab` and `searxng`
tool is annotated `readOnlyHint: true`. Of the `opengist`, `docmost` and
`silverbullet` tools, those that only add data are marked `(writes)` and
those that can replace or remove data `(destructive)`.
"""


async def section(title: str, app) -> tuple[str, int]:
    async with Client(app) as c:
        tools = (await c.list_tools()).tools
    rows = []
    for t in tools:
        props = t.input_schema.get("properties", {})
        lines = [
            textwrap.fill(
                f"- `{k}`: {s['description']}" if s.get("description") else f"- `{k}`",
                78,
                subsequent_indent="  ",
            )
            for k, s in props.items()
        ]
        params = "Parameters:\n\n" + "\n".join(lines) if lines else "Parameters: none"
        desc = textwrap.fill(" ".join(t.description.split()), 78)
        ann = t.annotations
        kind = (
            "" if ann.read_only_hint else " (destructive)" if ann.destructive_hint else " (writes)"
        )
        label = f": {t.title}" if t.title else ""
        rows.append(f"\n### `{t.name}`{label}{kind}\n\n{params}\n\n{desc}\n")
    return f"\n## {title}\n" + "".join(rows), len(rows)


OUT = Path(__file__).resolve().parents[4] / "docs" / "TOOLS.md"
# claude plugin eval answers mocked tools from evals/mocks/<server>/; a saved
# tools/list there gives them their real names, descriptions and schemas.
MOCKS = Path(__file__).resolve().parents[2] / "evals" / "mocks"
SERVERS = {
    "homelab": server,
    "opengist": opengist,
    "docmost": docmost,
    "silverbullet": silverbullet,
    "searxng": searxng,
}


async def tool_lists() -> dict[Path, str]:
    """Each server's tools/list response as the _tools.json text for its mocks."""
    cfg = config.load("/nonexistent")
    out: dict[Path, str] = {}
    for name, module in SERVERS.items():
        async with Client(module.build(cfg)) as c:
            tools = (await c.list_tools()).tools
        listing = {
            "tools": [t.model_dump(mode="json", by_alias=True, exclude_none=True) for t in tools]
        }
        out[MOCKS / name / "_tools.json"] = json.dumps(listing, indent=2, sort_keys=True) + "\n"
    return out


async def render() -> tuple[str, int]:
    """The TOOLS.md text and the tool count, from a server built without config."""
    cfg = config.load("/nonexistent")
    parts = [
        await section("`homelab` server", server.build(cfg)),
        await section("`opengist` server", opengist.build(cfg)),
        await section("`docmost` server", docmost.build(cfg)),
        await section("`silverbullet` server", silverbullet.build(cfg)),
        await section("`searxng` server", searxng.build(cfg)),
    ]
    return HEADER + "".join(p for p, _ in parts), sum(n for _, n in parts)


async def main() -> None:
    text, count = await render()
    OUT.write_text(text)
    print(f"wrote {OUT} ({count} tools)")
    for path, listing in (await tool_lists()).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(listing)
        print(f"wrote {path}")


if __name__ == "__main__":
    asyncio.run(main())
