"""Regenerate docs/TOOLS.md from the registered tools: uv run python tools/gen_tools_doc.py"""

import asyncio
import textwrap
from pathlib import Path

from mcp import Client

from homelab_mcp import config, server

HEADER = """# Tools of the `homelab` server

Generated by `plugins/homelab/server/tools/gen_tools_doc.py`; do not edit by
hand. Every tool is annotated `readOnlyHint: true`.
"""


async def main() -> None:
    async with Client(server.build(config.load("/nonexistent"))) as c:
        tools = (await c.list_tools()).tools
    rows = []
    for t in tools:
        props = t.input_schema.get("properties", {})
        params = ", ".join(f"`{k}`" for k in props) or "none"
        desc = textwrap.fill(" ".join(t.description.split()), 78)
        rows.append(f"\n## `{t.name}`\n\nParameters: {params}\n\n{desc}\n")
    out = Path(__file__).resolve().parents[4] / "docs" / "TOOLS.md"
    out.write_text(HEADER + "".join(rows))
    print(f"wrote {out} ({len(rows)} tools)")


asyncio.run(main())
